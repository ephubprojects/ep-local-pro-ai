const CORS = {
  'Content-Type': 'application/json',
  'Access-Control-Allow-Origin': '*',
  'Access-Control-Allow-Headers': 'Content-Type'
};
const ok  = d        => ({ statusCode: 200, headers: CORS, body: JSON.stringify(d) });
const err = (m, c=400) => ({ statusCode: c, headers: CORS, body: JSON.stringify({ error: m }) });

// ─── HTML receipt builder ──────────────────────────────────────────────────────
function buildHtmlReceipt({ receiptNumber, bizName, bizAddress, bizPhone, customerName, items, total, paymentMethod, paidAt }) {
  const dateStr = new Date(paidAt).toLocaleString('en-US', {
    year: 'numeric', month: 'long', day: 'numeric',
    hour: '2-digit', minute: '2-digit'
  });

  const rows = (items || []).map(i => {
    const qty      = Number(i.qty || 1);
    const price    = Number(i.price || 0);
    const lineTotal = qty * price;
    return `
      <tr>
        <td style="padding:9px 12px;border-bottom:1px solid #f0f0f0;">${i.name || ''}</td>
        <td style="padding:9px 12px;border-bottom:1px solid #f0f0f0;text-align:center;">${qty}</td>
        <td style="padding:9px 12px;border-bottom:1px solid #f0f0f0;text-align:right;">$${price.toFixed(2)}</td>
        <td style="padding:9px 12px;border-bottom:1px solid #f0f0f0;text-align:right;">$${lineTotal.toFixed(2)}</td>
      </tr>`;
  }).join('');

  return `<!DOCTYPE html>
<html>
<head>
  <meta charset="utf-8">
  <title>Receipt ${receiptNumber}</title>
</head>
<body style="font-family:Arial,sans-serif;background:#f5f5f5;margin:0;padding:30px;">
  <div style="max-width:520px;margin:0 auto;background:#fff;border-radius:8px;overflow:hidden;box-shadow:0 2px 12px rgba(0,0,0,0.08);">

    <!-- Header -->
    <div style="padding:32px 28px;text-align:center;border-bottom:1px solid #eee;">
      <h1 style="margin:0 0 4px;font-size:26px;color:#1a1a2e;">${bizName}</h1>
      <div style="display:inline-block;background:#16a34a;color:#fff;font-size:16px;font-weight:bold;letter-spacing:3px;padding:6px 20px;border-radius:4px;margin-top:10px;">RECEIPT</div>
    </div>

    <!-- Meta -->
    <div style="padding:18px 28px;background:#fafafa;border-bottom:1px solid #eee;display:flex;justify-content:space-between;flex-wrap:wrap;gap:8px;font-size:13px;color:#555;">
      <div>
        <span style="color:#999;">Receipt #</span> <strong>${receiptNumber}</strong>
      </div>
      <div>
        <span style="color:#999;">Date</span> ${dateStr}
      </div>
      ${paymentMethod ? `<div><span style="color:#999;">Payment</span> <strong>${paymentMethod}</strong></div>` : ''}
    </div>

    ${customerName ? `
    <div style="padding:14px 28px;border-bottom:1px solid #eee;">
      <span style="font-size:12px;text-transform:uppercase;color:#999;letter-spacing:1px;">Customer: </span>
      <strong style="font-size:14px;color:#1a1a2e;">${customerName}</strong>
    </div>` : ''}

    <!-- Items -->
    <div style="padding:20px 28px;">
      <table style="width:100%;border-collapse:collapse;">
        <thead>
          <tr style="background:#f8f8f8;">
            <th style="padding:9px 12px;text-align:left;font-size:12px;color:#888;text-transform:uppercase;">Item</th>
            <th style="padding:9px 12px;text-align:center;font-size:12px;color:#888;text-transform:uppercase;">Qty</th>
            <th style="padding:9px 12px;text-align:right;font-size:12px;color:#888;text-transform:uppercase;">Price</th>
            <th style="padding:9px 12px;text-align:right;font-size:12px;color:#888;text-transform:uppercase;">Total</th>
          </tr>
        </thead>
        <tbody>${rows}</tbody>
      </table>
    </div>

    <!-- Total -->
    <div style="padding:16px 28px 24px;text-align:right;border-top:2px solid #1a1a2e;">
      <span style="font-size:14px;color:#666;text-transform:uppercase;letter-spacing:1px;">Amount Paid: </span>
      <span style="font-size:28px;font-weight:bold;color:#16a34a;">$${Number(total).toFixed(2)}</span>
    </div>

    <!-- Thank You -->
    <div style="padding:20px 28px;text-align:center;background:#f0fdf4;border-top:1px solid #dcfce7;">
      <p style="margin:0;font-size:16px;font-weight:bold;color:#16a34a;">Thank you for your business!</p>
    </div>

    <!-- Business Contact -->
    <div style="padding:18px 28px;text-align:center;border-top:1px solid #eee;font-size:13px;color:#888;">
      <strong style="color:#1a1a2e;">${bizName}</strong>
      ${bizAddress ? `<br>${bizAddress}` : ''}
      ${bizPhone   ? `<br>${bizPhone}`   : ''}
      <br><br><span style="font-size:11px;">Generated by EP Local Pro AI &bull; eplocalproai.com</span>
    </div>

  </div>
</body>
</html>`;
}

// ─── Handler ───────────────────────────────────────────────────────────────────
exports.handler = async (event) => {
  if (event.httpMethod === 'OPTIONS') return { statusCode: 204, headers: CORS, body: '' };
  if (event.httpMethod !== 'POST') return err('Method not allowed', 405);

  let body;
  try { body = JSON.parse(event.body || '{}'); }
  catch { return err('Invalid JSON'); }

  const {
    bizName, bizAddress = '', bizPhone = '',
    customerName = '',
    items = [],
    total,
    paymentMethod = '',
    orderId = ''
  } = body;

  if (!bizName) return err('bizName is required');
  if (!items.length) return err('items array is required and must not be empty');
  if (total === undefined || total === null) return err('total is required');

  const receiptNumber = `REC-${Date.now().toString(36).toUpperCase().slice(-6)}`;
  const paidAt        = new Date().toISOString();

  const htmlContent = buildHtmlReceipt({
    receiptNumber, bizName, bizAddress, bizPhone,
    customerName, items, total: Number(total),
    paymentMethod, paidAt
  });

  return ok({
    receiptNumber,
    type: 'receipt',
    bizName,
    customerName,
    total: Number(total),
    paymentMethod,
    orderId,
    paidAt,
    htmlContent
  });
};
